[CmdletBinding()]
param(
    [switch]$Check
)

$ErrorActionPreference = "Stop"
$repositoryRoot = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot ".."))
$featuresRoot = Join-Path $repositoryRoot "oPenEfficiency\Features"
$outputPath = Join-Path $repositoryRoot "oPenEfficiency\UI\Panels\MainSidebar.GeneratedCommands.cs"

$specializedIds = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
@(
    "BtnFlightMode",
    "BtnRepeatShape"
) | ForEach-Object { [void]$specializedIds.Add($_) }

$registrations = [System.Collections.Generic.List[object]]::new()
$excluded = [System.Collections.Generic.List[string]]::new()

foreach ($file in Get-ChildItem -LiteralPath $featuresRoot -Recurse -Filter *.cs -File) {
    $source = [System.IO.File]::ReadAllText($file.FullName)
    $namespaceMatch = [regex]::Match($source, 'namespace\s+(?<name>[A-Za-z0-9_.]+)')
    if (-not $namespaceMatch.Success) { continue }
    $namespace = $namespaceMatch.Groups['name'].Value
    $attributes = [regex]::Matches(
        $source,
        '(?s)\[FeatureMetadata\((?<args>.*?)\)\s*\]\s*public\s+static\s+class\s+(?<class>\w+)')

    for ($index = 0; $index -lt $attributes.Count; $index++) {
        $attribute = $attributes[$index]
        $idMatch = [regex]::Match($attribute.Groups['args'].Value, 'Id\s*=\s*"(?<id>[^"]+)"')
        if (-not $idMatch.Success) { continue }
        $id = $idMatch.Groups['id'].Value
        $isToggle = [regex]::IsMatch($attribute.Groups['args'].Value, 'IsToggle\s*=\s*true')
        if ($isToggle -or $specializedIds.Contains($id)) {
            $excluded.Add($id)
            continue
        }

        $segmentEnd = if ($index + 1 -lt $attributes.Count) {
            $attributes[$index + 1].Index
        } else {
            $source.Length
        }
        $segment = $source.Substring($attribute.Index, $segmentEnd - $attribute.Index)
        $methods = [regex]::Matches(
            $segment,
            'public\s+static\s+(?<return>bool|void)\s+Execute\s*\((?<params>[^)]*)\)')
        $callable = $null
        foreach ($method in $methods) {
            $parameters = @($method.Groups['params'].Value -split ',' | ForEach-Object { $_.Trim() })
            if ($parameters.Count -eq 0 -or $parameters[0] -notmatch 'PowerPointManager\s+\w+') { continue }
            $allOptional = $true
            for ($parameterIndex = 1; $parameterIndex -lt $parameters.Count; $parameterIndex++) {
                if ($parameters[$parameterIndex] -notmatch '=') {
                    $allOptional = $false
                    break
                }
            }
            if ($parameters.Count -eq 1 -or $allOptional) {
                $callable = $method
                if ($parameters.Count -eq 1) { break }
            }
        }

        if ($null -eq $callable) {
            $excluded.Add($id)
            continue
        }

        $registrations.Add([pscustomobject]@{
            Id = $id
            Type = "$namespace.$($attribute.Groups['class'].Value)"
            ReturnsVoid = $callable.Groups['return'].Value -eq 'void'
        })
    }
}

$builder = [Text.StringBuilder]::new()
[void]$builder.AppendLine("// <auto-generated>")
[void]$builder.AppendLine("// Generated by eng/GenerateCommandRegistrations.ps1. Do not edit by hand.")
[void]$builder.AppendLine("// </auto-generated>")
[void]$builder.AppendLine("using oPenEfficiency.Services.Commands;")
[void]$builder.AppendLine()
[void]$builder.AppendLine("namespace oPenEfficiency")
[void]$builder.AppendLine("{")
[void]$builder.AppendLine("    public partial class MainSidebar")
[void]$builder.AppendLine("    {")
[void]$builder.AppendLine("        private static void RegisterGeneratedFeatureCommands(CommandRegistry registry)")
[void]$builder.AppendLine("        {")
foreach ($registration in $registrations | Sort-Object Id) {
    $method = if ($registration.ReturnsVoid) { "RegisterVoidAction" } else { "RegisterAction" }
    [void]$builder.AppendLine(
        "            $method(registry, `"$($registration.Id)`", context => $($registration.Type).Execute(context.PowerPoint));")
}
[void]$builder.AppendLine("        }")
[void]$builder.AppendLine("    }")
[void]$builder.AppendLine("}")

$content = $builder.ToString().Replace("`r`n", "`n")
if ($Check) {
    if (-not (Test-Path -LiteralPath $outputPath) -or
        [System.IO.File]::ReadAllText($outputPath).Replace("`r`n", "`n") -ne $content) {
        throw "Generated command registrations are stale. Run eng/GenerateCommandRegistrations.ps1."
    }
} else {
    [System.IO.File]::WriteAllText($outputPath, $content, [Text.UTF8Encoding]::new($false))
}

if ($Check) { Write-Host "COMMAND_REGISTRATIONS_CURRENT registrations=$($registrations.Count)" } else { Write-Host "COMMAND_REGISTRATIONS_GENERATED registrations=$($registrations.Count)" }
Write-Host "Specialized or non-default commands: $($excluded.Count) ($([string]::Join(', ', ($excluded | Sort-Object))))"
